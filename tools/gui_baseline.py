"""The preset results shipped with the package (``src/mmw60/data/gui/baseline/``): what the page
opens on before anything is computed.

    python tools/gui_baseline.py build [--jobs 4]     # run the four jobs at full size on the presets, write them
    python tools/gui_baseline.py import DIR           # take job results written by tools/gui_report.py --json
    python tools/gui_baseline.py check                # is the shipped baseline in step with this tree?

The baseline is data generated by code, never edited by hand.  ``check`` (also a test) fails when
the spec tables or a vendored pin changed since it was computed, when a file is missing, or when it
is not a full-size preset run; ``tests/test_guistore.py`` further compares its numbers with
``examples/expected``.  Rebuild it whenever a change moves numbers (the same moment the examples'
expected outputs are re-accepted): about 10 minutes with ``--jobs 4`` on a 4-core machine.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from mmw60 import ENGINE_BANNER, guistore, guiutil  # noqa: E402

#: the file name tools/gui_report.py is asked to write for each job when a directory is imported
IMPORT_NAMES = {"table": "table.json", "calibration_be": "calibration.json", "array": "array.json", "ay": "ay.json"}


def _run(job: str) -> dict:
    return guiutil.run_job(job, {})


def normalise(result: dict) -> dict:
    """A job result as the baseline stores it: the fields ``run_job`` writes, whatever wrote it."""
    out = dict(result)
    out.setdefault("built_on", {})
    out.setdefault("quick", False)
    return out


def write(results: dict[str, dict], directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    for job, res in results.items():
        why = guistore.stale_reasons(res)
        if why:
            raise SystemExit(f"{job}: not a baseline ({'; '.join(why)})")
        path = directory / f"{job}.json"
        path.write_text(guistore.dumps(normalise(res)) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)} ({path.stat().st_size} bytes, computed in {res['seconds']:.0f} s)")


def check(directory: Path) -> list[str]:
    """Everything wrong with the shipped baseline, as lines; empty when it is in step."""
    have = guistore.load_baseline(directory)
    bad = [f"{job}: missing ({directory / (job + '.json')})" for job in guistore.BASELINE_JOBS if job not in have]
    for job, res in have.items():
        bad += [f"{job}: {why}" for why in guistore.stale_reasons(res)]
        if res.get("job") != job:
            bad.append(f"{job}: the file holds a {res.get('job')!r} result")
        if sorted(res.get("parts", [])) != sorted(guiutil.JOBS[job]["parts"]):
            bad.append(f"{job}: parts {res.get('parts')} are not the job's {list(guiutil.JOBS[job]['parts'])}")
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("what", choices=("build", "import", "check"))
    ap.add_argument("source", nargs="?", type=Path, help="import: the directory holding the job results")
    ap.add_argument("--jobs", type=int, default=1, help="build: jobs side by side")
    ap.add_argument("--dir", type=Path, default=guistore.BASELINE_DIR, help="the baseline directory")
    a = ap.parse_args(argv)
    print(ENGINE_BANNER)
    if a.what == "check":
        bad = check(a.dir)
        for line in bad:
            print("  " + line)
        print("baseline: " + ("OUT OF STEP — rebuild with tools/gui_baseline.py build" if bad else "in step"))
        return 1 if bad else 0
    t0 = time.time()
    if a.what == "import":
        if a.source is None:
            raise SystemExit("import wants the directory")
        results = {job: json.loads((a.source / name).read_text(encoding="utf-8")) for job, name in IMPORT_NAMES.items()}
    elif a.jobs > 1:
        with ProcessPoolExecutor(max_workers=a.jobs) as pool:
            results = dict(zip(guistore.BASELINE_JOBS, pool.map(_run, guistore.BASELINE_JOBS)))
    else:
        results = {job: _run(job) for job in guistore.BASELINE_JOBS}
    write(results, a.dir)
    print(f"[{time.time() - t0:.0f}s]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
