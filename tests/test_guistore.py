REPO = Path(__file__).resolve().parent.parent
EXPECTED = REPO / "examples" / "expected"
OBO = {"frontend.pa.obo_db": 9.5}


def result(job: str, st: dict, built_on=None, parts=None, quick=False) -> dict:
    out = g.job_result(job, st, {"kind": g.JOBS[job]["report"]}, seconds=1.0, parts=parts, built_on=built_on)
    out["quick"] = quick
    return out


# ------------------------------------------------------------------ what a result was really built on
def test_a_result_records_the_upstream_results_it_was_built_on_not_the_ones_its_study_names():
    """A table computed for a new back-off without a calibration for it looked its IRR up in the
    accepted table: it is built on the *preset* calibration, and redoing the calibration afterwards
    must not make it read fresh."""
    tab = result("table", OBO)
    assert tab["built_on"] == {}
    env = g.envelopes_of(tab)["table.analytic"]
    assert env["upstream"]["calibration.be"] == g.signature("calibration.be", {}) != g.signature("calibration.be", OBO)
    cal = g.envelopes_of(result("calibration_be", OBO))
    f = g.freshness(OBO, {**cal, **g.envelopes_of(tab)})
    assert f["calibration.be"]["state"] == "fresh"
    assert f["table.analytic"]["state"] == "stale" and f["table.analytic"]["upstream"] == ["calibration.be"]
    assert f["table.analytic"]["changed"] == []                       # its own knobs are the study's
    # rebuilt on that calibration it is fresh
    f = g.freshness(OBO, {**cal, **g.envelopes_of(result("table", OBO, built_on={"calibration.be": OBO}))})
    assert f["table.analytic"]["state"] == "fresh"
    # a result stored before ``built_on`` existed was built on the presets
    old = {k: v for k, v in tab.items() if k != "built_on"}
    assert g.envelopes_of(old) == g.envelopes_of(tab)


# ------------------------------------------------------------------ the store
def test_pick_prefers_the_result_whose_parts_hold_for_the_study_then_the_fuller_then_the_newer(tmp_path):
    base = {"table": result("table", {}), "calibration_be": result("calibration_be", {})}
    store = guistore.Store(tmp_path, base)
    assert store.pick("table", {})["id"] == "baseline-table" and store.pick("array", {}) is None
    # the form moves: the baseline is still what is shown (stale), nothing vanishes
    assert store.pick("table", OBO)["id"] == "baseline-table"
    rid = store.add(result("table", OBO))
    assert store.pick("table", OBO)["id"] == rid and store.pick("table", {})["id"] == "baseline-table"
    # a third study: the newest computed result is shown before the baseline
    other = {"frontend.pa.obo_db": 10.0}
    assert store.pick("table", other)["id"] == rid
    # an analytic-only run for that study holds one part; the full ones hold none of theirs
    part = store.add(result("table_analytic", other, parts=["table.analytic"]))
    assert store.pick("table", other)["id"] == part
    # a smoke-size result is kept but never shown
    q = store.add(result("table", {"frontend.pa.obo_db": 11.0}, quick=True))
    assert store.pick("table", {"frontend.pa.obo_db": 11.0})["id"] != q
    env = store.envelopes(OBO)
    assert set(env) == {"table.analytic", "table.td", "table.ay", "calibration.be"}
    assert env["table.td"]["study"] == OBO and env["calibration.be"]["study"] == {}


def test_results_persist_under_home_replace_themselves_and_the_baseline_cannot_be_deleted(tmp_path):
    store = guistore.Store(tmp_path, {"ay": result("ay", {})})
    rid = store.add(result("calibration_be", OBO))
    assert store.add(result("calibration_be", OBO)) == rid                 # the same job for the same study: one file
    assert [p.name for p in (tmp_path / "results").iterdir()] == [f"{rid}.json"]
    assert store.add(result("table", OBO, built_on={"calibration.be": OBO})) != store.add(result("table", OBO))
    (tmp_path / "results" / "notes.json").write_text("{}")                 # not ours: ignored, left alone
    (tmp_path / "results" / "table-000000000000.json").write_text(json.dumps(dict(result("table", {}), schema=0)))
    again = guistore.Store(tmp_path, {"ay": result("ay", {})})
    rows = again.listing(OBO)
    assert [r["origin"] for r in rows].count("user") == 3 and rows[0]["id"] == "baseline-ay"
    assert {r["id"]: r["shown"] for r in rows}[rid]
    assert all(isinstance(r["report"], str) for r in rows)                 # the report's name, never the report
    assert not again.delete("baseline-ay") and again.delete(rid) and not again.delete(rid)
    assert not (tmp_path / "results" / f"{rid}.json").exists() and (tmp_path / "results" / "notes.json").exists()
    mem = guistore.Store(None, {})
    assert mem.add(result("ay", {})) and mem.listing() and mem.home is None


def test_default_home_follows_the_environment(monkeypatch, tmp_path):
    monkeypatch.setenv("MMW60_HOME", str(tmp_path / "h"))
    assert guistore.default_home() == tmp_path / "h"
    monkeypatch.delenv("MMW60_HOME")
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path / "c"))
    monkeypatch.delenv("LOCALAPPDATA", raising=False)
    assert guistore.default_home() == tmp_path / "c" / "mmw60"


def test_stale_reasons_name_what_moved_under_a_stored_result():
    ok = result("table", {})
    assert guistore.stale_reasons(ok) == []
    assert "spec tables" in guistore.stale_reasons(dict(ok, provenance=dict(ok["provenance"], spec_digest="0")))[0]
    moved = json.loads(json.dumps(ok))
    next(iter(moved["provenance"]["vendored"].values()))["pin"] = "0" * 40
    assert "pin" in guistore.stale_reasons(moved)[0]
    assert guistore.stale_reasons(dict(ok, schema=0)) and guistore.stale_reasons(result("table", OBO))
    assert guistore.stale_reasons(result("table", {}, quick=True)) == ["a smoke-size run"]


# ------------------------------------------------------------------ the shipped baseline
BASELINE = guistore.load_baseline()


def _accepted(name: str) -> list[str]:
    """An accepted example output without what is not a number of the run: the engine line, the
    timer, blank lines, trailing blanks."""
    lines = (EXPECTED / f"{name}.txt").read_text(encoding="utf-8").splitlines()
    return [ln.rstrip() for ln in lines[1:] if ln.strip() and not re.fullmatch(r"\[.*s\]", ln.strip())]


def _example(name: str):
    spec = importlib.util.spec_from_file_location(f"example_{name[:2]}", REPO / "examples" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _printed(fn) -> list[str]:
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        fn()
    return [ln.rstrip() for ln in buf.getvalue().splitlines() if ln.strip()]


def test_the_shipped_baseline_is_in_step_with_this_tree():
    """Missing, computed on other spec tables or pins, a smoke run, not the presets: all red.  The
    fix is ``python tools/gui_baseline.py build``, at the moment the examples are re-accepted."""
