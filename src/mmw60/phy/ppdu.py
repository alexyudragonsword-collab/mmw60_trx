"""VHT data field: PSDU bytes → scrambled, BCC-coded, interleaved, mapped data symbols, and back.

The OFDM symbols themselves are generated by wifitrx (``generate_ofdm`` with
explicit constellation points); this module only produces and consumes the
(n_symbols, n_active) point array, with the pilots at wifitrx's
``pilot_positions`` columns and the 52 data tones in increasing frequency
order around them.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from . import bcc, interleaver, mapper, scrambler
from .mcs import N_SERVICE, N_TAIL, VhtMcs


@dataclass(frozen=True)
class DataField:
    mcs: VhtMcs
    psdu: np.ndarray              # uint8 bits, 8 * psdu_bytes
    tx_bits: np.ndarray           # scrambled encoder input (service + psdu + tail + pad)
    symbols: np.ndarray           # (n_symbols, n_active) complex points incl. pilots
    data_cols: np.ndarray         # column indices of the data tones
    pilot_cols: np.ndarray
    pilots: np.ndarray            # (n_symbols, n_pilots) known pilot values
    scrambler_seed: int

    @property
    def n_symbols(self) -> int:
        return int(self.symbols.shape[0])

    @property
    def psdu_bytes(self) -> int:
        return int(self.psdu.size // 8)


def random_psdu(n_bytes: int, rng: np.random.Generator) -> np.ndarray:
    return rng.integers(0, 2, size=8 * int(n_bytes)).astype(np.uint8)


def encoder_input(psdu_bits: np.ndarray, mcs: VhtMcs, seed: int) -> np.ndarray:
    """SERVICE (16 zero) + PSDU + 6 tail + pad, scrambled, tail re-zeroed."""
    n_bytes = psdu_bits.size // 8
    n_sym = mcs.n_symbols(n_bytes)
    n_total = n_sym * mcs.n_dbps
    bits = np.zeros(n_total, dtype=np.uint8)
    bits[N_SERVICE:N_SERVICE + psdu_bits.size] = psdu_bits
    scr = scrambler.scramble(bits, seed)
    t0 = N_SERVICE + psdu_bits.size
    scr[t0:t0 + N_TAIL] = 0          # tail bits are not scrambled (they flush the encoder)
    return scr


def build_data_field(mcs: VhtMcs, psdu_bits: np.ndarray, n_active: int,
                     pilot_cols: np.ndarray, pilots: np.ndarray,
                     scrambler_seed: int = scrambler.DEFAULT_SEED) -> DataField:
    psdu_bits = np.asarray(psdu_bits, dtype=np.uint8)
    pilot_cols = np.asarray(pilot_cols, dtype=int)
    data_cols = np.setdiff1d(np.arange(n_active), pilot_cols)
    if data_cols.size != mcs.n_sd:
        raise ValueError(f"{data_cols.size} data tones in the plan, MCS table expects {mcs.n_sd}")
    tx_bits = encoder_input(psdu_bits, mcs, scrambler_seed)
    coded = bcc.puncture(bcc.encode(tx_bits), (mcs.rate.numerator, mcs.rate.denominator))
    n_sym = mcs.n_symbols(psdu_bits.size // 8)
    if coded.size != n_sym * mcs.n_cbps:
        raise AssertionError((coded.size, n_sym, mcs.n_cbps))
    inter = interleaver.interleave(coded.reshape(n_sym, mcs.n_cbps), mcs.n_bpscs, mcs.n_sd)
    pts = mapper.map_bits(inter.reshape(-1), mcs.qam_order).reshape(n_sym, mcs.n_sd)
    pilots = np.asarray(pilots, dtype=complex)
    if pilots.shape != (n_sym, pilot_cols.size):
        raise ValueError(f"pilots must be ({n_sym}, {pilot_cols.size}), got {pilots.shape}")
    symbols = np.empty((n_sym, n_active), dtype=complex)
    symbols[:, data_cols] = pts
    symbols[:, pilot_cols] = pilots
    return DataField(mcs=mcs, psdu=psdu_bits, tx_bits=tx_bits, symbols=symbols,
                     data_cols=data_cols, pilot_cols=pilot_cols, pilots=pilots,
                     scrambler_seed=scrambler_seed)


def decode_data_field(eq_symbols: np.ndarray, field: DataField,
                      weight: np.ndarray | float = 1.0,
                      kernel: str | None = None) -> tuple[np.ndarray, int]:
    """Equalised (n_symbols, n_active) points → (decoded PSDU bits, bit errors).

    ``weight`` is per data tone (length N_SD) or scalar: |H_k|²/σ² after
    zero-forcing, so a faded tone's LLRs count less."""
    mcs = field.mcs
    y = np.asarray(eq_symbols, dtype=complex)[:, field.data_cols]       # (n_sym, n_sd)
    n_sym = y.shape[0]
    w = np.asarray(weight, dtype=float)
    if w.ndim:
        w = np.broadcast_to(w.reshape(1, -1), (n_sym, mcs.n_sd)).reshape(-1)
    soft = mapper.llr(y.reshape(-1), mcs.qam_order, w)                  # (n_sym*n_sd*m,)
    soft = interleaver.deinterleave(soft.reshape(n_sym, mcs.n_cbps), mcs.n_bpscs, mcs.n_sd)
    n_info = field.tx_bits.size
    llr_full = bcc.depuncture(soft.reshape(-1), (mcs.rate.numerator, mcs.rate.denominator),
                              2 * n_info)
    dec = bcc.viterbi_decode(llr_full, kernel=kernel)
    desc = scrambler.descramble(dec, field.scrambler_seed)
    psdu_hat = desc[N_SERVICE:N_SERVICE + field.psdu.size]
    errors = int(np.count_nonzero(psdu_hat != field.psdu))
    return psdu_hat, errors
