"""Where computed results live, and which of them a page shows for a study.

``guiutil`` computes and never touches a disk; a host (``webhost``) queues the
jobs; this module keeps what they returned.  Two places:

* the **baseline** shipped with the package (``data/gui/baseline/<job>.json``):
  the four jobs run at full size on the presets, so a page opens on the
  comparison table without computing anything.  It is data generated by code
  (``tools/gui_baseline.py build``) and guarded against drifting from the code
  that would compute it (``stale_reasons`` here; ``tests/test_guistore.py``
  compares its numbers with ``examples/expected``);
* the **user's results** (``<home>/results/<job>-<key>.json``): what the queue
  computed for other studies.  ``home`` is ``MMW60_HOME`` or a per-user cache
  directory; a store with ``home=None`` keeps them in memory only (tests, a
  read-only install).

``Store.pick(report, study)`` is the one rule for which stored result a page
draws: the one with the most parts still fresh for the study, a full run
before a partial one, the newest before an older one — so a form that has
moved on keeps showing the last numbers, marked stale by ``guiutil.freshness``,
rather than nothing.
"""
from __future__ import annotations

import hashlib
import json
import os
import threading
import time
from pathlib import Path

from . import guiutil

BASELINE_DIR = guiutil.PACKAGE / "data" / "gui" / "baseline"
#: the jobs the baseline carries (``table_analytic`` is a part of ``table``)
BASELINE_JOBS = ("table", "calibration_be", "array", "ay")
#: the report a page asks for -> the jobs whose results can answer it
REPORT_JOBS = {name: tuple(j for j, v in guiutil.JOBS.items() if v["report"] == name)
               for name in sorted({v["report"] for v in guiutil.JOBS.values()})}


def default_home() -> Path:
    """``MMW60_HOME``, else the user's cache directory."""
    env = os.environ.get("MMW60_HOME")
    if env:
        return Path(env)
    base = os.environ.get("LOCALAPPDATA") or os.environ.get("XDG_CACHE_HOME")
    return Path(base or Path.home() / ".cache", "mmw60")


def result_key(result: dict) -> str:
    """Names a result by what it is: the job, the study, the upstream studies it was built on and
    whether it was a smoke-size run.  The same job run again for the same study replaces itself."""
    blob = json.dumps([result["job"], result["study"], result.get("built_on") or {}, bool(result.get("quick"))],
                      sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:12]


def dumps(result: dict) -> str:
    """Compact, keys in the order the report was built: that order is the order of the sections and
    of a row's columns, which the examples' printers and a page rely on."""
    return json.dumps(result, ensure_ascii=False, allow_nan=False, separators=(",", ":"))


def load_baseline(directory: Path | None = None) -> dict[str, dict]:
    """The shipped results by job; a missing file is simply absent (a source tree before the
    baseline was built)."""
    out = {}
    for job in BASELINE_JOBS:
        path = (directory or BASELINE_DIR) / f"{job}.json"
        if path.is_file():
            out[job] = json.loads(path.read_text(encoding="utf-8"))
    return out


def stale_reasons(result: dict) -> list[str]:
    """Why a stored result is not what this code would compute, as far as that can be told without
    computing it: another schema, another spec table, another vendored pin, a smoke-size run, a
    study that is not the presets.  Empty for a baseline that is in step with the tree."""
    now = guiutil.provenance()
    was = result.get("provenance", {})
    why = []
    if result.get("schema") != guiutil.SCHEMA:
        why.append(f"schema {result.get('schema')} != {guiutil.SCHEMA}")
    if was.get("spec_digest") != now["spec_digest"]:
        why.append("the spec tables changed since it was computed")
    if {k: v.get("pin") for k, v in (was.get("vendored") or {}).items()} != {k: v.get("pin")
                                                                           for k, v in now["vendored"].items()}:
        why.append("a vendored library's pin changed since it was computed")
    if result.get("quick"):
        why.append("a smoke-size run")
    if result.get("study"):
        why.append(f"not the presets: {result['study']}")
    return why


class Store:
    """Stored job results: the shipped baseline plus the user's own."""

    def __init__(self, home: str | Path | None = None, baseline: dict[str, dict] | None = None):
        self.home = None if home is None else Path(home)
        self._lock = threading.Lock()
        self._results: dict[str, dict] = {}                 # id -> {"id", "origin", "at", "result"}
        for job, res in (load_baseline() if baseline is None else baseline).items():
            self._results[f"baseline-{job}"] = {"id": f"baseline-{job}", "origin": "baseline", "at": 0.0, "result": res}
        if self.home is not None and self.dir.is_dir():
            for path in sorted(self.dir.glob("*.json")):
                try:
                    res = json.loads(path.read_text(encoding="utf-8"))
                    rid = f"{res['job']}-{result_key(res)}"
                    if res.get("schema") == guiutil.SCHEMA and path.stem == rid:
                        self._results[rid] = {"id": rid, "origin": "user", "at": path.stat().st_mtime, "result": res}
                except (OSError, ValueError, KeyError):
                    continue                                    # not one of ours: leave it alone

    @property
    def dir(self) -> Path:
        return self.home / "results"

    # ------------------------------------------------------------ writing
    def add(self, result: dict) -> str:
        """Keep a job result (and write it under ``home``); returns its id."""
        rid = f"{result['job']}-{result_key(result)}"
        entry = {"id": rid, "origin": "user", "at": time.time(), "result": result}
        if self.home is not None:
            self.dir.mkdir(parents=True, exist_ok=True)
            tmp = self.dir / f".{rid}.tmp"
            tmp.write_text(dumps(result), encoding="utf-8")
            tmp.replace(self.dir / f"{rid}.json")
        with self._lock:
            self._results[rid] = entry
        return rid

    def delete(self, rid: str) -> bool:
        """Forget one of the user's results; the baseline cannot be deleted."""
        with self._lock:
            entry = self._results.get(rid)
            if entry is None or entry["origin"] != "user":
                return False
            del self._results[rid]
        if self.home is not None:
            (self.dir / f"{rid}.json").unlink(missing_ok=True)
        return True

    # ------------------------------------------------------------ reading
    def entries(self) -> list[dict]:
        with self._lock:
            return list(self._results.values())

    def get(self, rid: str) -> dict | None:
        with self._lock:
            return self._results.get(rid)

    def pick(self, report: str, st: dict | None = None) -> dict | None:
        """The stored result a page draws for ``report`` (``table`` / ``calibration`` / ``array`` /
        ``ay``) under study ``st``; None when nothing is stored for it.  Smoke-size results are
        never picked."""
        st = guiutil.study(st)
        best, best_rank = None, None
        for entry in self.entries():
            res = entry["result"]
            if res["job"] not in REPORT_JOBS[report] or res.get("quick"):
                continue
            own = guiutil.envelopes_of(res)
            fresh = guiutil.freshness(st, own)
            rank = (sum(1 for p in res["parts"] if not fresh[p]["changed"]),      # parts whose own knobs still hold
                    sum(1 for p in res["parts"] if fresh[p]["state"] == "fresh"),
                    len(res["parts"]), entry["at"])
            if best_rank is None or rank > best_rank:
                best, best_rank = entry, rank
        return best

    def envelopes(self, st: dict | None = None) -> dict[str, dict]:
        """One envelope per part from the results a page shows for ``st`` (what ``freshness`` reads)."""
        out: dict[str, dict] = {}
        for report in REPORT_JOBS:
            entry = self.pick(report, st)
            if entry is not None:
                out.update(guiutil.envelopes_of(entry["result"]))
        return out

    def listing(self, st: dict | None = None) -> list[dict]:
        """Every stored result without its report: id, job, study, where and when it was computed,
        and whether it is the one shown for ``st``."""
        shown = {e["id"] for e in (self.pick(r, st) for r in REPORT_JOBS) if e is not None}
        rows = []
        for entry in sorted(self.entries(), key=lambda e: (e["at"], e["id"])):
            res = entry["result"]
            rows.append({"id": entry["id"], "origin": entry["origin"], "at": entry["at"], "job": res["job"],
                         "report": guiutil.JOBS[res["job"]]["report"], "study": res["study"], "parts": res["parts"],
                         "built_on": res.get("built_on") or {}, "seconds": res.get("seconds"),
                         "quick": bool(res.get("quick")), "shown": entry["id"] in shown,
                         "version": res["provenance"].get("version"), "commit": res["provenance"].get("commit"),
                         "out_of_step": stale_reasons(res) if entry["origin"] == "baseline" else []})
        return rows
